import { mkdir, mkdtemp, rm, utimes, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { listClaudeSessions } from './sessions.js';

// Invented Claude Code sessions: `projects/<encoded cwd>/<session id>.jsonl`, in the shapes
// Claude Code writes its lines.

let configDir: string;

beforeEach(async () => {
  configDir = await mkdtemp(path.join(tmpdir(), 'wow-claude-sessions-'));
});

afterEach(async () => {
  await rm(configDir, { recursive: true, force: true });
});

async function session(folder: string, name: string, lines: unknown[], modified: string) {
  const dir = path.join(configDir, 'projects', folder);
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, name);
  await writeFile(
    file,
    lines.map((line) => (typeof line === 'string' ? line : JSON.stringify(line))).join('\n'),
  );
  await utimes(file, new Date(modified), new Date(modified));
}

const user = (content: unknown, extra: Record<string, unknown> = {}) => ({
  type: 'user',
  cwd: '/work/kettle',
  sessionId: 'invented',
  message: { role: 'user', content },
  ...extra,
});

describe('listClaudeSessions (agent workbench spec 72)', () => {
  it('lists each session with its id, folder, first prompt and time, newest first', async () => {
    await session(
      '-work-kettle',
      'aaaa-1111.jsonl',
      [
        { type: 'summary', summary: 'Invented summary' },
        user('Caveat: the messages below were generated by the user', { isMeta: true }),
        user('<command-name>/review</command-name>\n<command-args>src/bell.ts</command-args>'),
      ],
      '2026-11-02T08:00:00.000Z',
    );
    await session(
      '-work-kettle',
      'bbbb-2222.jsonl',
      [
        '{"type":"user","cwd":',
        user([{ type: 'text', text: 'Make the kettle\n  whistle   twice' }]),
        user('A later message'),
      ],
      '2026-11-03T08:00:00.000Z',
    );
    expect(await listClaudeSessions(configDir, { limit: 10, promptChars: 200 })).toEqual([
      {
        id: 'bbbb-2222',
        cwd: '/work/kettle',
        firstPrompt: 'Make the kettle whistle twice',
        lastUsedAt: '2026-11-03T08:00:00.000Z',
      },
      {
        id: 'aaaa-1111',
        cwd: '/work/kettle',
        firstPrompt: '/review src/bell.ts',
        lastUsedAt: '2026-11-02T08:00:00.000Z',
      },
    ]);
  });

  it('skips tool results and subagent lines, keeps only the newest sessions and cuts the prompt', async () => {
    await session(
      '-work-kettle',
      'cccc.jsonl',
      [
        user([{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }]),
        user('Agent work', { isSidechain: true }),
        user('Descale the kettle before the guests arrive'),
      ],
      '2026-11-05T08:00:00.000Z',
    );
    await session(
      '-work-kettle',
      'agent-dddd.jsonl',
      [user('A subagent transcript')],
      '2026-11-06T08:00:00.000Z',
    );
    await session('-work-kettle', 'old.jsonl', [user('Old')], '2026-10-01T08:00:00.000Z');
    expect(await listClaudeSessions(configDir, { limit: 1, promptChars: 11 })).toEqual([
      {
        id: 'cccc',
        cwd: '/work/kettle',
        firstPrompt: 'Descale the…',
        lastUsedAt: '2026-11-05T08:00:00.000Z',
      },
    ]);
  });

  it('decodes the folder name for a session with no cwd and no prompt, and answers nothing without a projects folder', async () => {
    await session('-work-tea', 'eeee.jsonl', [{ type: 'summary' }], '2026-11-01T08:00:00.000Z');
    expect(await listClaudeSessions(configDir, { limit: 5, promptChars: 50 })).toEqual([
      { id: 'eeee', cwd: '/work/tea', firstPrompt: null, lastUsedAt: '2026-11-01T08:00:00.000Z' },
    ]);
    expect(
      await listClaudeSessions(path.join(configDir, 'missing'), { limit: 5, promptChars: 50 }),
    ).toEqual([]);
  });
});
